// Generate only used Tabler icon exports so Vite avoids scanning the full package.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "src");
const iconDir = path.join(root, "node_modules/@tabler/icons-react/dist/esm/icons");
const names = new Set();
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).forEach((entry) => {
  const file = path.join(dir, entry.name);
  if (entry.isDirectory()) return walk(file);
  if (!/\.(tsx?|jsx?)$/.test(entry.name) || entry.name === "icons.js") return;
  for (const match of fs.readFileSync(file, "utf8").matchAll(/import\s*\{([^}]*)\}\s*from\s*["']@tabler\/icons-react["']/g)) {
    for (const name of match[1].split(",").map((item) => item.trim()).filter(Boolean)) names.add(name);
  }
});
walk(src);
const missing = [];
const exports = [...names].sort().filter((name) => fs.existsSync(path.join(iconDir, `${name}.mjs`)) || (missing.push(name), false))
  .map((name) => `export { default as ${name} } from "../node_modules/@tabler/icons-react/dist/esm/icons/${name}.mjs";`);
if (missing.length) throw new Error(`Missing Tabler icons: ${missing.join(", ")}`);
fs.writeFileSync(path.join(src, "icons.js"), `// Generated by scripts/gen-icons.mjs. Do not edit by hand.\n${exports.join("\n")}\n`);
console.log(`icons.js: ${exports.length} icons`);
