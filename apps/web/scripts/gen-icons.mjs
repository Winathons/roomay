// Regenerates src/icons.js: re-exports only the Tabler icons imported anywhere in src/.
// Run after adding an icon import:  npm run icons
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const src = path.join(root, "src");
const iconDir = path.join(root, "node_modules/@tabler/icons-react/dist/esm/icons");
const names = new Set();
const walk = d => fs.readdirSync(d, { withFileTypes: true }).forEach(e => {
  const p = path.join(d, e.name);
  if (e.isDirectory()) return walk(p);
  if (!/\.(tsx?|jsx?)$/.test(e.name) || e.name === "icons.js") return;
  for (const m of fs.readFileSync(p, "utf8").matchAll(/import\s*\{([^}]*)\}\s*from\s*"@tabler\/icons-react"/g))
    for (const n of m[1].split(",").map(x => x.trim()).filter(Boolean)) names.add(n);
});
walk(src);
const missing = [];
const lines = [...names].sort().filter(n => fs.existsSync(path.join(iconDir, `${n}.mjs`)) || (missing.push(n), false))
  .map(n => `export { default as ${n} } from "../node_modules/@tabler/icons-react/dist/esm/icons/${n}.mjs";`);
fs.writeFileSync(path.join(src, "icons.js"), "// Generated by scripts/gen-icons.mjs. Do not edit by hand.\n" + lines.join("\n") + "\n");
console.log(`icons.js: ${lines.length} icons${missing.length ? `; not found: ${missing.join(", ")}` : ""}`);
